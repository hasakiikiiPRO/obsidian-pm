let locale: Lang = 'en'

export function setLocale(lang: Lang): void {
  locale = lang
}

export function getLocale(): Lang {
  return locale
}

/** Reads Obsidian's interface language; falls back to English. */
export function detectLang(): Lang {
  try {
    const lang = getLanguage() ?? ''
    if (lang.toLowerCase().startsWith('zh')) return 'zh'
  } catch {
    /* ignore */
  }
  return 'en'
}

/** Resolves a message for the active locale, falling back to English then the key itself. */
export function t(key: string, vars?: Record<string, string | number>): string {
  const dict = locale === 'zh' ? zh : en
  const template = dict[key] ?? en[key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    vars[name] !== undefined ? String(vars[name]) : match
  )
}

/** Selects `key.one` or `key.other` by count and fills `{count}`. */
export function tPlural(count: number, key: string): string {
  return t(count === 1 ? `${key}.one` : `${key}.other`, { count })
}
